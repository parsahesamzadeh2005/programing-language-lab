year = int(input("لطفا یک سال وارد کنید: "))

# بررسی کبیسه بودن سال طبق قوانین ریاضی
if year % 4 == 0:
    
    # اگر بر ۱۰۰ بخش‌پذیر بود، حتماً باید بر ۴۰۰ هم بخش‌پذیر باشد
    if year % 100 == 0:
        
        if year % 400 == 0:
            print("سال کبیسه است.")
        else:
            print("سال کبیسه نیست.")
            
    else:
        # بر ۴ بخش‌پذیر است و بر ۱۰۰ هم نیست
        print("سال کبیسه است.")
        
else:
    # بر ۴ بخش‌پذیر نیست
    print("سال کبیسه نیست.")